/* ---------------- Timesheets ---------------- */
function buildTimesheets(attendance: AttendanceRecord[]): Timesheet[] {
  const out: Timesheet[] = [];
  const activeTasks = tasks.filter((t) => t.status !== "created" && t.status !== "cancelled");
  for (const task of activeTasks) {
    for (const empId of task.assigneeIds) {
      const days = attendance
        .filter(
          (a) =>
            a.employeeId === empId &&
            a.date >= task.createdAt.slice(0, 10) &&
            (a.status === "present" || a.status === "late" || a.status === "wfh")
        )
        .slice(-5);
      for (const day of days) {
        if (rnd() < 0.35) continue;
        const startMin = 10 * 60 + between(0, 60);
        const durMin = between(90, 300);
        const endMin = startMin + durMin;
        const startTime = `${pad2(Math.floor(startMin / 60))}:${pad2(startMin % 60)}`;
        const endTime = `${pad2(Math.floor(endMin / 60))}:${pad2(endMin % 60)}`;
        const isRecent = day.date >= daysAgo(2);
        out.push({
          id: uid("ts"),
          employeeId: empId,
          projectId: task.projectId,
          taskId: task.id,
          date: day.date,
          startTime,
          endTime,
          hours: minutesToHours(durMin),
          description: `${task.title} — progress update`,
          status: isRecent ? (rnd() < 0.5 ? "pending" : "approved") : "approved",
          approverId: isRecent ? undefined : "emp-rahul",
          decidedAt: isRecent ? undefined : day.date + "T19:30:00",
          overtime: durMin > 300,
        });
      }
    }
  }
  return out;
}

